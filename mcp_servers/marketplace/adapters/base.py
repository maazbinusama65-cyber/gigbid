"""Server-side marketplace adapter contract (every method is scoped to a ``user``)."""
from __future__ import annotations

from typing import Any, Protocol


class AdapterError(Exception):
    """Normalised upstream failure. ``code`` is surfaced to the agent as '<code>: <message>'.

    Codes: not_found, upstream_rate_limited, upstream_unavailable, upstream_rejected,
    unsupported, unauthorized.
    """

    def __init__(self, code: str, message: str, retry_after: float | None = None) -> None:
        super().__init__(f"{code}: {message}")
        self.code, self.message, self.retry_after = code, message, retry_after


class MarketplaceAdapter(Protocol):
    name: str

    async def search_jobs(self, user: str, *, q: str | None, category: str | None,
                          skills: list[str] | None, since: str | None, limit: int,
                          cursor: str | None) -> dict[str, Any]: ...
    async def get_job(self, user: str, job_id: str) -> dict[str, Any]: ...
    async def get_client(self, user: str, client_id: str) -> dict[str, Any]: ...
    async def get_connects(self, user: str) -> dict[str, Any]: ...
    async def get_market_stats(self, user: str, category: str | None,
                               skills: list[str] | None) -> dict[str, Any]: ...
    async def get_policy(self, user: str) -> dict[str, Any]: ...
    async def list_messages(self, user: str, thread_id: str | None) -> dict[str, Any]: ...
    async def list_events(self, user: str, since: str | None) -> list[dict[str, Any]]: ...
    async def get_proposal(self, user: str, proposal_id: str) -> dict[str, Any]: ...
    async def create_proposal(self, user: str, payload: dict[str, Any], idempotency_key: str,
                              dry_run: bool) -> dict[str, Any]: ...
    async def submit_proposal(self, user: str, proposal_id: str, idempotency_key: str) -> dict[str, Any]: ...
    async def send_message(self, user: str, thread_id: str, body: str,
                           idempotency_key: str) -> dict[str, Any]: ...
    async def aclose(self) -> None: ...
